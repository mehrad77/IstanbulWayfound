import type { Locale, ProfileBundle } from "@wayfound/core";
import type { BusinessSeed } from "./types.ts";

/** Resolve seed data into a ProfileBundle without a database (tests, static builds). */
export function bundleFromSeed(
  seed: BusinessSeed,
  locale: Locale,
  updatedAt = "2026-10-24T09:00:00.000Z",
): ProfileBundle {
  return {
    locale,
    business: {
      id: seed.id,
      slug: seed.slug,
      vertical: seed.vertical,
      schemaType: seed.schemaType,
      name: seed.name,
      tagline: seed.text.tagline[locale],
      description: seed.text.description[locale],
      howToFindUs: seed.text.howToFindUs[locale],
      phone: seed.phone,
      whatsapp: seed.whatsapp,
      email: seed.email,
      website: seed.website,
      languages: seed.languages,
      priceRange: seed.priceRange,
      rating: seed.rating,
      reviewLinks: seed.reviewLinks,
      wayfindingVideoUrl: null,
      logoUrl: null,
      isDemo: true,
      updatedAt,
    },
    location: { ...seed.location, city: "İstanbul", country: "TR" },
    categories: seed.categories.map((c, ci) => ({
      id: c.id,
      name: c.name[locale],
      position: ci,
      items: c.items.map((i, ii) => ({
        id: i.id,
        categoryId: c.id,
        sku: i.sku ?? null,
        name: i.name[locale],
        description: i.description[locale],
        priceKurus: i.priceKurus,
        priceFrom: i.priceFrom ?? false,
        durationMin: i.durationMin ?? null,
        soldOut: i.soldOut ?? false,
        photoUrl: null,
        dietary: i.dietary ?? [],
        allergens: i.allergens ?? [],
        fabric: i.fabric ?? null,
        sizes: i.sizes ?? [],
        moq: i.moq ?? null,
        position: ii,
        updatedAt,
      })),
    })),
    faqs: seed.faqs.map((f) => ({
      id: f.id,
      question: f.question[locale],
      answer: f.answer[locale],
    })),
    team: seed.team.map((t) => ({
      id: t.id,
      name: t.name,
      title: t.title[locale],
      credentials: t.credentials[locale],
      languages: t.languages,
    })),
    packages: seed.packages.map((p, pi) => ({
      id: p.id,
      slug: p.slug,
      name: p.name[locale],
      summary: p.summary[locale],
      procedureName: p.procedureName[locale],
      daysInIstanbul: p.daysInIstanbul,
      visits: p.visits,
      priceFromKurus: p.priceFromKurus,
      priceFactors: p.priceFactors[locale],
      languages: p.languages,
      inclusions: p.inclusions,
      steps: p.steps.map((s, si) => ({
        id: `${p.id}_s${si + 1}`,
        stage: s.stage,
        owner: s.owner,
        dayLabel: s.dayLabel[locale],
        title: s.title[locale],
        detail: s.detail[locale],
        position: si,
      })),
      faqs: p.faqs.map((f) => ({
        id: f.id,
        question: f.question[locale],
        answer: f.answer[locale],
      })),
      published: true,
      position: pi,
    })),
  };
}
